// Builds data/replay/golden.json from the scripted model so `npm run measure` has something to
// replay before anyone has run it live. The file is marked synthetic and the measure output
// says so. A live run overwrites it with real responses.
import { loadGolden } from "../src/golden.ts";
import { VIBECODER } from "../src/profile.ts";
import { evaluate } from "../src/harness.ts";
import { recordingClient, type ReplayEntry } from "../src/providers/replay.ts";
import { scriptedClient } from "../src/scripted.ts";
import { MATRIX, REPLAY_PATH, writeJson } from "./_setup.ts";

const golden = loadGolden();
const entries: ReplayEntry[] = [];
const client = recordingClient(scriptedClient(golden.articles), entries);
for (const opts of MATRIX) await evaluate(client, opts, VIBECODER, golden);
writeJson(REPLAY_PATH, {
  synthetic: true,
  note: "generated by src/scripted.ts from the golden labels with seeded noise; not model output",
  recordedAt: new Date().toISOString().slice(0, 10),
  entries,
});
console.log(`wrote ${entries.length} synthetic entries to data/replay/golden.json`);
